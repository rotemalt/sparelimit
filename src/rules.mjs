/** Everything that decides what the ledger counts, as plain data. */
export function rulesSnapshot() {
  return { version: LEDGER_RULES_VERSION, thresholds: { ...L }, families: FAMILIES.map((f) => ({ ...f })), statuses: [...STATUSES], text: RULE_TEXT.map((r) => ({ id: r.id, text: r.text })) };
}

/**
 * JSON with keys in sorted order, so the fingerprint does not depend on how the code orders them.
 * @returns {string}
 */
function canonical(/** @type {any} */ v) {
  if (Array.isArray(v)) return `[${v.map(canonical).join(",")}]`;
  if (v && typeof v === "object") return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canonical(v[k])}`).join(",")}}`;
  return JSON.stringify(v);
}

/** A fingerprint of the rules: the SHA-256 of their canonical JSON. */
export const rulesHash = (/** @type {any} */ snap = rulesSnapshot()) => crypto.createHash("sha256").update(canonical(snap)).digest("hex");

